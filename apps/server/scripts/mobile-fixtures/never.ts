import path from 'node:path';
import Database from 'better-sqlite3';
import { createHarness } from '@songie/game-kit/testing';
import { defaultSettings, type NeverView } from '@songie/never/shared';
import { neverServer } from '@songie/never/server';
import { fixtureWriter } from './lib.js';

const out = fixtureWriter('never');
const repo = path.resolve(import.meta.dirname, '../../../..');
const game = neverServer({ db: new Database(':memory:'), contentDir: path.join(repo, 'games/never/server/test-content'), timing: { podiumMs: 5000, finalRevealMs: 3000 } });
const settings = { ...defaultSettings, categories: ['genel'], seconds: 30, rounds: 2, lives: 3 };
const h = createHarness<NeverView>(game, { players: ['ali', 'ayse', 'cem'], settings });
await h.start();
out.write('question-host', h.view('ali'), { settings });
const sid = () => h.view('ali').statement!.id;
await h.act('ali', { type: 'answer', statementId: sid(), answer: 'did' });
out.write('question-answered', h.view('ali'), { settings });
out.write('question-guest', h.view('cem'), { settings });
await h.act('ayse', { type: 'answer', statementId: sid(), answer: 'did' });
await h.act('cem', { type: 'answer', statementId: sid(), answer: 'didNot' });
out.write('reveal-host', h.view('ali'), { settings });
out.write('reveal-guest', h.view('cem'), { settings });
await h.act('ali', { type: 'next', statementId: sid() });
for (const id of ['ali', 'ayse', 'cem']) await h.act(id, { type: 'answer', statementId: sid(), answer: 'did' });
out.write('reveal-final', h.view('ali'), { settings });
await h.act('ali', { type: 'next', statementId: sid() });
h.advance(3500);
out.write('podium', h.view('ayse'), { settings });
out.done();
